const withFallback = (dict: Partial<Dictionary>): Dictionary => ({
  ...en,
  ...dict,
}) as Dictionary;

const translations: Record<LanguageCode, Dictionary> = {
  en: withFallback(en),
  tr: withFallback(tr),
  de: withFallback(de),
  it: withFallback(it),
  es: withFallback(es),
  "zh-CN": withFallback(zhCN),
  bn: withFallback(bn),
  vi: withFallback(vi),
  hi: withFallback(hi),
  ur: withFallback(ur),
};

const LanguageContext = createContext<I18nContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<LanguageCode>("en");

  useEffect(() => {
    const stored = localStorage.getItem("np_language");
    if (stored && stored in translations) setLanguage(stored as LanguageCode);
  }, []);

  useEffect(() => {
    localStorage.setItem("np_language", language);
  }, [language]);

  const value = useMemo(() => {
    const dict = translations[language] ?? translations.en;
    return {
      language,
      setLanguage,
      t: (key: string) => dict[key] ?? translations.en[key] ?? key,
    };
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useI18n must be used within LanguageProvider");
  return ctx;
}

